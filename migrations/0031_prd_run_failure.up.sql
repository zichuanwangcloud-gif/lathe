-- 0031_prd_run_failure — PRD 后台轮次的失败记录
--
-- 问题：规划轮次与对抗复核原来跑在同步 HTTP 请求里（一轮 3~10 分钟），
-- 失败原因只能经响应体回给发起请求的那个页面。刷新、换标签页、网络抖一下，
-- 请求一断 agent 就被取消，失败原因也无处可查 —— 服务端日志不记、
-- prd_events 里只有被截断的事件流。
--
-- 轮次改到后台跑之后（docs/10 §1.4），响应体里已经没有错误可回。界面靠
-- 轮询 prds 行判断「跑完了没有、跑成了没有」，所以失败要落在行上：
--
--   last_error        上一次后台运行（规划轮次或对抗复核）为什么失败。
--   last_error_input  那一次人说的话：失败不推进轮次，这句话没有别处
--                     落脚（prd_rounds 只记成功的轮次），界面据此放回输入框。
--
-- 两列都只描述「最近一次运行」，下一次抢占（BeginPRDRound）时清空。
-- 不做成历史表：失败的完整过程已经在 prd_events 里（按轮号可查），这里
-- 只是给界面的一个当前值，与 processing 同一性质。
--
-- 两列都可空、无默认值：存量行语义上就是「没有失败记录」，无需回填。
ALTER TABLE prds
  ADD COLUMN last_error       text,
  ADD COLUMN last_error_input text;
